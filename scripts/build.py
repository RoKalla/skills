#!/usr/bin/env python3
"""Keep the skills in sync with their shared sources.

1. Fills every `<!-- BEGIN SHARED: x -->` ... `<!-- END SHARED: x -->` block in
   skills/*/SKILL.md with shared/x.md.
2. Generates skills/rk-full-review/SKILL.md from templates/rk-full-review.md.

Usage:
  python3 scripts/build.py          # write the files
  python3 scripts/build.py --check  # exit 1 if any file is out of date (CI)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "templates" / "rk-full-review.md"
GENERATED = ROOT / "skills" / "rk-full-review" / "SKILL.md"
NOTICE = (
    "<!-- GENERATED by scripts/build.py from templates/rk-full-review.md. "
    "Edit the sources and run `python3 scripts/build.py`. -->\n"
)

BLOCK = re.compile(r"(<!-- BEGIN SHARED: (\S+) -->\n)(.*?)(<!-- END SHARED: \2 -->)", re.S)
FRONTMATTER = re.compile(r"\A---\n.*?\n---\n", re.S)
INCLUDE = re.compile(r"\{\{(shared|body):(\S+?)\}\}")


def shared(name: str) -> str:
    return (ROOT / "shared" / f"{name}.md").read_text().strip() + "\n"


def sync_blocks(text: str) -> str:
    return BLOCK.sub(lambda m: m.group(1) + shared(m.group(2)) + m.group(4), text)


def demote_headings(text: str) -> str:
    """Push markdown headings one level down, leaving fenced code alone."""
    out, fenced = [], False
    for line in text.splitlines(keepends=True):
        if line.startswith("```"):
            fenced = not fenced
        elif not fenced and re.match(r"#+ ", line):
            line = "#" + line
        out.append(line)
    return "".join(out)


def body(text: str) -> str:
    """A skill's instructions for inclusion: no frontmatter, no shared blocks."""
    text = BLOCK.sub("", FRONTMATTER.sub("", text))
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    return demote_headings(text)


def build() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for path in sorted((ROOT / "skills").glob("*/SKILL.md")):
        if path != GENERATED:
            out[path] = sync_blocks(path.read_text())

    def include(m: re.Match) -> str:
        kind, arg = m.groups()
        if kind == "shared":
            return shared(arg).strip()
        return body(out[ROOT / arg])

    rendered = INCLUDE.sub(include, TEMPLATE.read_text())
    frontmatter = FRONTMATTER.match(rendered).group(0)
    out[GENERATED] = frontmatter + "\n" + NOTICE + rendered[len(frontmatter):]
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for path, content in build().items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if check and stale:
        print("Out of date (run `python3 scripts/build.py`):")
        for p in stale:
            print(f"  {p}")
        return 1
    for p in stale:
        print(f"updated {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
